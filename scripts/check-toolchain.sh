#!/usr/bin/env bash
# 检查本机工具链是否与 versions.env 对齐。CI 与本地都跑。

source "$(dirname "$0")/lib.sh"
source "$(dirname "$0")/versions.env"

begin "cwgo ${CWGO_VERSION}"
if ! command -v cwgo >/dev/null 2>&1; then
  fail "cwgo not found in PATH"
  printf '    install: go install %s@%s\n' "$CWGO_MODULE" "$CWGO_VERSION"
else
  got="$(cwgo --version 2>&1 | head -1)"
  case "$got" in
    *"$CWGO_VERSION"*) pass ;;
    *) fail "got '$got', want $CWGO_VERSION" ;;
  esac
fi

begin "PATH 里的 kitex 不参与生成"
if command -v kitex >/dev/null 2>&1; then
  printf 'present (%s), ignored: fixtures only use cwgo\n' "$(kitex -version 2>&1 | head -1 | tr -d '\n')"
fi
pass

begin "fixture 运行时版本与 versions.env 一致"
for mod in fixtures/kitex-greet/app/greet fixtures/hertz-greet/app/apigw; do
  kitex_got="$(cd "$REPO_ROOT/$mod" && go list -m -f '{{.Version}}' github.com/cloudwego/kitex 2>/dev/null || echo none)"
  hertz_got="$(cd "$REPO_ROOT/$mod" && go list -m -f '{{.Version}}' github.com/cloudwego/hertz 2>/dev/null || echo none)"
  case "$mod" in
    *apigw) want_kitex="$KITEX_RUNTIME_VERSION"; want_hertz="$HERTZ_RUNTIME_VERSION" ;;
    *) want_kitex="$KITEX_RUNTIME_VERSION"; want_hertz="none" ;;
  esac
  [ "$kitex_got" = "$want_kitex" ] || { fail "$mod: kitex $kitex_got != $want_kitex"; continue; }
  [ "$hertz_got" = "$want_hertz" ] || { fail "$mod: hertz $hertz_got != $want_hertz"; continue; }
done
pass

begin "生成物标记的生成器版本"
marker="$(grep -rho 'Code generated by Kitex v[0-9.]*' "$REPO_ROOT"/fixtures/*/rpc_gen/kitex_gen 2>/dev/null | sort -u | head -1)"
case "$marker" in
  *"v$KITEX_GENERATOR_VERSION"*|*"${KITEX_GENERATOR_VERSION}"*) pass ;;
  *) fail "generator marker '$marker' != $KITEX_GENERATOR_VERSION" ;;
esac

summary
